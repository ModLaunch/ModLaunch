const I18N = {
  lang: 'ru',
  STRINGS,

  set(lang) {
    I18N.lang = lang === 'en' ? 'en' : 'ru';
    if (typeof document !== 'undefined') document.documentElement.lang = I18N.lang;
    return I18N.lang;
  },

  /**
   * @param {string} key
   * @param {Record<string, string|number>} [params]
   */
  t(key, params = {}) {
    const table = STRINGS[I18N.lang] ?? STRINGS.ru;
    const template = table[key] ?? STRINGS.ru[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name) =>
      name in params ? String(params[name]) : match
    );
  },

  /** Число словами там, где русскому нужно согласование, а английскому — нет. */
  plural(n, one, few, many) {
    if (I18N.lang === 'en') return n === 1 ? one : few;
    const m10 = n % 10;
    const m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return one;
    if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
    return many;
  },
};

if (typeof window !== 'undefined') window.I18N = I18N;
if (typeof module !== 'undefined' && module.exports) module.exports = I18N;
