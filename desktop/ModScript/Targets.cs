using System.IO.Compression;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using ModLaunch.Creator;

namespace ModScriptX;

/// <summary>Файл, который получился из .modx: путь относительно папки игры и текст.</summary>
public sealed record OutFile(string Path, string Text, byte[]? Bytes = null);

/// <summary>
/// Движок игры: свой язык, свой способ подключить мод и свои события.
/// Всё ставится через штатные загрузчики модов и папки скриптов игры.
/// </summary>
public abstract class Target
{
    public abstract string Id { get; }
    public abstract string Title { get; }
    public abstract string Language { get; }
    public virtual string[] Events => ModxDoc.Events;

    public static readonly Target[] All = [new RenPy(), new RpgMaker(), new Unity(), new Godot(), new LuaMods()];
    public static Target? Find(string id) => All.FirstOrDefault(t => t.Id == id || t.Aliases.Contains(id));
    protected virtual string[] Aliases => [];

    /// <summary>Файлы мода. gameDir нужен движкам, у которых путь зависит от игры (RPG Maker MV/MZ, Unity).</summary>
    public abstract List<OutFile> Emit(ModxDoc doc, string? gameDir);

    /// <summary>Шаг после копирования файлов (например, запись в plugins.js). Возвращает, что сделано.</summary>
    public virtual string? AfterInstall(ModxDoc doc, string gameDir) => null;
    public virtual void AfterEject(string id, string gameDir) { }

    protected Lang L => Lang.For(Language);

    protected static string Header(ModxDoc d, string comment) =>
        $"{comment} {d.Name} {d.Version}{(d.Author != "" ? " by " + d.Author : "")} — generated by ModScript X from a {ModxDoc.Extension} script.\n" +
        $"{comment} Edit the .modx file, not this one: it is overwritten on every inject.\n";

    protected void Warn(ModxDoc d)
    {
        foreach (var h in d.Hooks.Where(h => !Events.Contains(h.Event)))
            d.Diags.Add(new Diag(h.Line, $"hook '{h.Event}' is not available for {Title}", true));
        foreach (var n in d.Natives.Where(n => n.Lang != Language))
            d.Diags.Add(new Diag(n.Line, $"native {n.Lang} block skipped: {Title} uses {Language}", true));
    }

    protected IEnumerable<string> NativeCode(ModxDoc d) => d.Natives.Where(n => n.Lang == Language).Select(n => n.Code);

    /// <summary>Тело хука на языке движка. say/log у каждого движка свои.</summary>
    protected void Body(Code w, List<Stmt> body, Func<string, string> say, Func<string, string> log)
    {
        var l = L;
        var semi = Language is "javascript" or "csharp" ? ";" : "";
        var indentLang = Language is "python" or "gdscript";
        var empty = new Stack<bool>();
        empty.Push(true);
        void Line(string s) { w.Line(s + semi); empty.Pop(); empty.Push(false); }
        void Close() { if (indentLang && empty.Peek()) w.Line("pass"); empty.Pop(); w.Out(); }
        foreach (var s in body)
        {
            switch (s.Kind)
            {
                case "set": Line($"{s.Target} = {l.Expr(s.Expr)}"); break;
                case "add": Line(Language == "lua" ? $"{s.Target} = {s.Target} + ({l.Expr(s.Expr)})" : $"{s.Target} += {l.Expr(s.Expr)}"); break;
                case "say": Line(say(l.Expr(s.Expr))); break;
                case "log": Line(log(l.Expr(s.Expr))); break;
                case "call": Line(l.Expr(s.Expr)); break;
                case "if":
                    empty.Pop(); empty.Push(false);
                    var c = l.Expr(s.Expr);
                    w.Line(Language switch { "lua" => $"if {c} then", "python" or "gdscript" => $"if {c}:", _ => $"if ({c}) {{" });
                    w.In(); empty.Push(true);
                    break;
                case "else":
                    Close();
                    w.Line(Language switch { "lua" => "else", "python" or "gdscript" => "else:", _ => "} else {" });
                    w.In(); empty.Push(true);
                    break;
                case "end":
                    Close();
                    if (!indentLang) w.Line(Language == "lua" ? "end" : "}");
                    break;
            }
        }
        if (indentLang && empty.Peek()) w.Line("pass");
    }

    // ---------------------------------------------------------------- Ren'Py

    sealed class RenPy : Target
    {
        public override string Id => "renpy";
        public override string Title => "Ren'Py";
        public override string Language => "python";

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("    ");
            w.Raw(Header(d, "#"));
            w.Line("init 999 python:");
            w.In();
            foreach (var (name, v) in d.Shared) w.Line($"{name} = {L.Literal(v)}");
            foreach (var code in NativeCode(d)) w.Block(code);
            foreach (var h in d.Hooks)
            {
                var fn = $"_modx_{d.Id}_{h.Event}";
                w.Line($"def {fn}(*args):");
                w.In();
                var globals = h.Body.Where(s => s.Kind is "set" or "add" && !s.Target.Contains('.') && !s.Target.Contains('[')).Select(s => s.Target).Distinct().ToList();
                if (globals.Count > 0) w.Line("global " + string.Join(", ", globals));
                Body(w, h.Body, e => $"renpy.notify({e})", e => $"print({e})");
                w.Out();
                w.Line(h.Event switch
                {
                    "ready" => $"{fn}()",
                    "start" => $"config.start_callbacks.append({fn})",
                    "load" => $"config.after_load_callbacks.append({fn})",
                    _ => $"config.periodic_callbacks.append({fn})",
                });
            }
            if (d.Shared.Count == 0 && d.Hooks.Count == 0 && !NativeCode(d).Any()) w.Line("pass");
            return [new OutFile($"game/modscript_{d.Id}.rpy", w.ToString())];
        }
    }

    // ---------------------------------------------------------------- RPG Maker MV / MZ

    sealed class RpgMaker : Target
    {
        public override string Id => "rpgmaker";
        public override string Title => "RPG Maker MV/MZ";
        public override string Language => "javascript";
        protected override string[] Aliases => ["rpgmv", "rpgmz"];

        /// <summary>У MV скрипты лежат в www/js, у MZ — сразу в js.</summary>
        static string JsDir(string? gameDir) => gameDir != null && Directory.Exists(Path.Combine(gameDir, "www", "js")) ? "www/js" : "js";
        static string PluginName(string id) => "ModScript_" + id;

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("  ");
            w.Raw("//=============================================================================\n");
            w.Raw(Header(d, "//"));
            w.Raw("//=============================================================================\n");
            w.Raw($"/*:\n * @target MZ\n * @plugindesc {(d.About != "" ? d.About : d.Name)} (ModScript X)\n * @author {(d.Author != "" ? d.Author : "ModScript X")}\n */\n");
            w.Line("(() => {");
            w.In();
            w.Line("\"use strict\";");
            foreach (var (name, v) in d.Shared) w.Line($"let {name} = {L.Literal(v)};");
            foreach (var code in NativeCode(d)) w.Block(code);
            foreach (var h in d.Hooks)
            {
                w.Line($"const {h.Event} = () => {{");
                w.In();
                Body(w, h.Body, e => $"$gameMessage.add(String({e}))", e => $"console.log({e})");
                w.Out();
                w.Line("};");
                var (owner, method, args) = h.Event switch
                {
                    "start" => ("DataManager", "setupNewGame", ""),
                    "load" => ("DataManager", "extractSaveContents", "contents"),
                    "tick" => ("Scene_Map.prototype", "update", ""),
                    _ => ("", "", ""),
                };
                if (owner == "") { w.Line($"{h.Event}();"); continue; }
                var saved = $"_{h.Event}_{method}";
                w.Line($"const {saved} = {owner}.{method};");
                w.Line($"{owner}.{method} = function({args}) {{");
                w.In();
                w.Line($"const result = {saved}.apply(this, arguments);");
                w.Line($"{h.Event}();");
                w.Line("return result;");
                w.Out();
                w.Line("};");
            }
            w.Out();
            w.Line("})();");
            return [new OutFile($"{JsDir(gameDir)}/plugins/{PluginName(d.Id)}.js", w.ToString())];
        }

        /// <summary>Плагин включается записью в js/plugins.js — как это делает сам редактор RPG Maker.</summary>
        public override string? AfterInstall(ModxDoc d, string gameDir)
        {
            var path = Path.Combine(gameDir, JsDir(gameDir), "plugins.js");
            if (!File.Exists(path)) return "plugins.js not found: enable the plugin in the RPG Maker editor";
            var text = File.ReadAllText(path);
            var name = PluginName(d.Id);
            if (text.Contains($"\"name\":\"{name}\"")) return null;
            var close = text.LastIndexOf(']');
            if (close < 0) return "plugins.js has an unexpected format: enable the plugin in the RPG Maker editor";
            var entry = JsonSerializer.Serialize(new { name, status = true, description = d.About, parameters = new { } });
            var before = text[..close].TrimEnd();
            var sep = before.EndsWith('[') ? "\n" : ",\n";
            File.WriteAllText(path, before + sep + entry + "\n" + text[close..]);
            return $"registered {name} in plugins.js";
        }

        public override void AfterEject(string id, string gameDir)
        {
            var path = Path.Combine(gameDir, JsDir(gameDir), "plugins.js");
            if (!File.Exists(path)) return;
            var lines = File.ReadAllLines(path).ToList();
            var i = lines.FindIndex(l => l.Contains($"\"name\":\"{PluginName(id)}\""));
            if (i < 0) return;
            lines.RemoveAt(i);
            // Убрать висячую запятую у предыдущей записи, если удалили последнюю.
            if (i < lines.Count && lines[i].TrimStart().StartsWith(']') && i > 0) lines[i - 1] = lines[i - 1].TrimEnd().TrimEnd(',');
            File.WriteAllLines(path, lines);
        }
    }

    // ---------------------------------------------------------------- Unity + BepInEx

    sealed class Unity : Target
    {
        public override string Id => "unity";
        public override string Title => "Unity (BepInEx 5)";
        public override string Language => "csharp";
        protected override string[] Aliases => ["bepinex"];

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var cls = "ModScript_" + d.Id;
            var w = new Code("    ");
            w.Raw(Header(d, "//"));
            w.Line("using BepInEx;");
            w.Line("using UnityEngine;");
            w.Line("using UnityEngine.SceneManagement;");
            w.Line("");
            w.Line($"[BepInPlugin(\"modscript.{d.Id.ToLowerInvariant()}\", {Plain(d.Name)}, {Plain(d.Version)})]");
            w.Line($"public class {cls} : BaseUnityPlugin");
            w.Line("{");
            w.In();
            foreach (var (name, v) in d.Shared) w.Line($"public static {Lang.CSharp.TypeOf(v)} {name} = {L.Literal(v)};");
            foreach (var code in NativeCode(d)) w.Block(code);
            var has = d.Hooks.Select(h => h.Event).ToHashSet();
            w.Line("bool _started;");
            w.Line("void Awake()");
            w.Line("{");
            w.In();
            if (has.Contains("start") || has.Contains("load")) w.Line("SceneManager.sceneLoaded += (scene, mode) => { if (!_started) { _started = true; OnStart(); } OnLoad(); };");
            w.Line("OnReady();");
            w.Out();
            w.Line("}");
            if (has.Contains("tick")) w.Line("void Update() => OnTick();");
            foreach (var ev in ModxDoc.Events)
            {
                w.Line($"void On{char.ToUpperInvariant(ev[0])}{ev[1..]}()");
                w.Line("{");
                w.In();
                foreach (var h in d.Hooks.Where(h => h.Event == ev))
                    Body(w, h.Body, e => $"Logger.LogMessage({e})", e => $"Logger.LogInfo({e})");
                w.Out();
                w.Line("}");
            }
            w.Out();
            w.Line("}");

            var managed = FindManaged(gameDir) ?? "$(GameDir)/Game_Data/Managed";
            var proj = $"""
                <Project Sdk="Microsoft.NET.Sdk">
                  <!-- {d.Name}: generated by ModScript X. Build: dotnet build -c Release -->
                  <PropertyGroup>
                    <TargetFramework>netstandard2.0</TargetFramework>
                    <AssemblyName>{cls}</AssemblyName>
                    <LangVersion>latest</LangVersion>
                    <GameDir>{gameDir ?? "PATH-TO-GAME"}</GameDir>
                    <OutputPath>$(GameDir)/BepInEx/plugins/</OutputPath>
                    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
                  </PropertyGroup>
                  <ItemGroup>
                    <Reference Include="BepInEx"><HintPath>$(GameDir)/BepInEx/core/BepInEx.dll</HintPath><Private>false</Private></Reference>
                    <Reference Include="UnityEngine"><HintPath>{managed}/UnityEngine.dll</HintPath><Private>false</Private></Reference>
                    <Reference Include="UnityEngine.CoreModule"><HintPath>{managed}/UnityEngine.CoreModule.dll</HintPath><Private>false</Private></Reference>
                  </ItemGroup>
                </Project>

                """;
            return
            [
                new OutFile($"BepInEx/modscript/{d.Id}/{cls}.cs", w.ToString()),
                new OutFile($"BepInEx/modscript/{d.Id}/{cls}.csproj", proj),
            ];
        }

        static string? FindManaged(string? gameDir) =>
            gameDir == null ? null : Directory.EnumerateDirectories(gameDir, "*_Data").Select(p => Path.Combine(p, "Managed")).FirstOrDefault(Directory.Exists)?.Replace('\\', '/');

        /// <summary>C# нужно собрать: если .NET SDK есть, собираем сразу в BepInEx/plugins.</summary>
        public override string? AfterInstall(ModxDoc d, string gameDir)
        {
            if (!Directory.Exists(Path.Combine(gameDir, "BepInEx", "core"))) return "BepInEx is not installed in this game: install BepInEx 5 first";
            var proj = Path.Combine(gameDir, "BepInEx", "modscript", d.Id, $"ModScript_{d.Id}.csproj");
            try
            {
                var psi = new System.Diagnostics.ProcessStartInfo("dotnet", $"build \"{proj}\" -c Release -nologo -v q") { RedirectStandardOutput = true, RedirectStandardError = true };
                using var p = System.Diagnostics.Process.Start(psi)!;
                var output = p.StandardOutput.ReadToEnd() + p.StandardError.ReadToEnd();
                p.WaitForExit();
                return p.ExitCode == 0 ? "built into BepInEx/plugins" : "build failed:\n" + output.Trim();
            }
            catch (System.ComponentModel.Win32Exception)
            {
                return $"install the .NET SDK and run: dotnet build \"{proj}\"";
            }
        }

        public override void AfterEject(string id, string gameDir)
        {
            var dll = Path.Combine(gameDir, "BepInEx", "plugins", $"ModScript_{id}.dll");
            if (File.Exists(dll)) File.Delete(dll);
        }
    }

    // ---------------------------------------------------------------- Godot Mod Loader

    sealed class Godot : Target
    {
        public override string Id => "godot";
        public override string Title => "Godot (Godot Mod Loader)";
        public override string Language => "gdscript";
        public override string[] Events => ["ready", "start", "tick"];

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var author = d.Author != "" ? System.Text.RegularExpressions.Regex.Replace(d.Author, @"[^\w]", "") : "ModScript";
            var folder = $"{author}-{d.Id}";
            var w = new Code("\t");
            w.Raw(Header(d, "#"));
            w.Line("extends Node");
            w.Line("");
            foreach (var (name, v) in d.Shared) w.Line($"var {name} = {L.Literal(v)}");
            foreach (var code in NativeCode(d)) w.Block(code);
            void Fn(string sig, string ev)
            {
                var hooks = d.Hooks.Where(h => h.Event == ev).ToList();
                if (hooks.Count == 0) return;
                w.Line(sig);
                w.In();
                foreach (var h in hooks) Body(w, h.Body, e => $"print({e})", e => $"print({e})");
                w.Out();
            }
            Fn("func _init():", "ready");
            Fn("func _ready():", "start");
            Fn("func _process(_delta):", "tick");
            var manifest = new JsonObject
            {
                ["name"] = d.Id,
                ["namespace"] = author,
                ["version_number"] = d.Version,
                ["description"] = d.About,
                ["website_url"] = "",
                ["dependencies"] = new JsonArray(),
                ["extra"] = new JsonObject { ["godot"] = new JsonObject { ["authors"] = new JsonArray(d.Author), ["compatible_mod_loader_version"] = new JsonArray("6.0.0"), ["compatible_game_version"] = new JsonArray(), ["incompatibilities"] = new JsonArray(), ["load_before"] = new JsonArray(), ["tags"] = new JsonArray(), ["config_schema"] = new JsonObject(), ["description_rich"] = "", ["image"] = null } },
            }.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
            // Собранная игра читает моды из mods/*.zip рядом с exe.
            using var ms = new MemoryStream();
            using (var zip = new ZipArchive(ms, ZipArchiveMode.Create, true))
            {
                void Add(string path, string text)
                {
                    using var s = zip.CreateEntry(path).Open();
                    s.Write(Encoding.UTF8.GetBytes(text));
                }
                Add($"mods-unpacked/{folder}/mod_main.gd", w.ToString());
                Add($"mods-unpacked/{folder}/manifest.json", manifest);
            }
            return [new OutFile($"mods/{folder}.zip", "", ms.ToArray())];
        }
    }

    // ---------------------------------------------------------------- игры с модами на Lua

    sealed class LuaMods : Target
    {
        public override string Id => "lua";
        public override string Title => "Lua mods (LÖVE and Lua-moddable games)";
        public override string Language => "lua";
        protected override string[] Aliases => ["love"];

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("  ");
            w.Raw(Header(d, "--"));
            w.Line("local M = {}");
            w.Line("-- say: a game can provide modx_host.say to show text in-game; otherwise it prints.");
            w.Line("local say = (modx_host and modx_host.say) or print");
            foreach (var (name, v) in d.Shared) w.Line($"{name} = {L.Literal(v)}");
            foreach (var code in NativeCode(d)) w.Block(code);
            foreach (var h in d.Hooks)
            {
                w.Line($"function M.{h.Event}({(h.Event == "tick" ? "dt" : "")})");
                w.In();
                Body(w, h.Body, e => $"say({e})", e => $"print({e})");
                w.Out();
                w.Line("end");
            }
            w.Line("-- LÖVE: chain into love.load / love.update when they exist.");
            w.Line("if love then");
            w.In();
            if (d.Hooks.Any(h => h.Event == "start")) w.Line("local _load = love.load; love.load = function(...) if _load then _load(...) end M.start() end");
            if (d.Hooks.Any(h => h.Event == "tick")) w.Line("local _update = love.update; love.update = function(dt) if _update then _update(dt) end M.tick(dt) end");
            w.Out();
            w.Line("end");
            if (d.Hooks.Any(h => h.Event == "ready")) w.Line("M.ready()");
            w.Line("return M");
            var dir = gameDir != null && Directory.Exists(Path.Combine(gameDir, "Mods")) ? "Mods" : "mods";
            return [new OutFile($"{dir}/{d.Id}.lua", w.ToString())];
        }
    }

    protected static string Plain(string s) => JsonSerializer.Serialize(s);
}

/// <summary>Писатель кода с отступами.</summary>
public sealed class Code(string unit)
{
    readonly StringBuilder sb = new();
    int depth;
    public void In() => depth++;
    public void Out() => depth = Math.Max(0, depth - 1);
    public void Line(string s) => sb.Append(s == "" ? "" : string.Concat(Enumerable.Repeat(unit, depth)) + s).Append('\n');
    public void Raw(string s) => sb.Append(s);
    /// <summary>Многострочная вставка (native) на текущем отступе.</summary>
    public void Block(string code) { foreach (var l in code.Split('\n')) Line(l); }
    public override string ToString() => sb.ToString();
}
