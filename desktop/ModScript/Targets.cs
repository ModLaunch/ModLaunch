/// <summary>Файл, который получился из .modx: путь относительно папки игры и текст.</summary>
public sealed record OutFile(string Path, string Text, byte[]? Bytes = null);

/// <summary>
/// Движок игры: свой язык, свой способ подключить мод и свои события.
/// Всё ставится через штатные загрузчики модов и папки скриптов игры.
/// </summary>
public abstract class Target
{
    public abstract string Id { get; }
    public abstract string Title { get; }
    public abstract string Language { get; }
    public virtual string[] Events => ModxDoc.Events;

    public static readonly Target[] All = [new RenPy(), new RpgMaker(), new Unity(), new Godot(), new LuaMods()];
    public static Target? Find(string id) => All.FirstOrDefault(t => t.Id == id || t.Aliases.Contains(id));
    protected virtual string[] Aliases => [];

    /// <summary>Файлы мода. gameDir нужен движкам, у которых путь зависит от игры (RPG Maker MV/MZ, Unity).</summary>
    public abstract List<OutFile> Emit(ModxDoc doc, string? gameDir);

    /// <summary>Шаг после копирования файлов (например, запись в plugins.js). Возвращает, что сделано.</summary>
    public virtual string? AfterInstall(ModxDoc doc, string gameDir) => null;
    public virtual void AfterEject(string id, string gameDir) { }

    protected Lang L => Lang.For(Language);

    protected static string Header(ModxDoc d, string comment) =>
        $"{comment} {Meta(d.Name)} {Meta(d.Version)}{(d.Author != "" ? " by " + Meta(d.Author) : "")} — generated by ModScript X from a {ModxDoc.Extension} script.\n" +
        $"{comment} Edit the .modx file, not this one: it is overwritten on every inject.\n";

    /// <summary>
    /// mod, version, author и about для комментария в коде движка: перевод строки вывел бы текст из комментария
    /// в код, «*/» закрыл бы блок /* */ RPG Maker, «--» — комментарий XML в .csproj.
    /// </summary>
    protected static string Meta(string s)
    {
        var t = new string(s.Select(c => char.IsControl(c) || c is '\u2028' or '\u2029' ? ' ' : c).ToArray());
        while (t.Contains("*/")) t = t.Replace("*/", "* /");
        while (t.Contains("--")) t = t.Replace("--", "- -");
        return t;
    }

    protected void Warn(ModxDoc d)
    {
        foreach (var h in d.Hooks.Where(h => !Events.Contains(h.Event)))
            d.Diags.Add(new Diag(h.Line, $"hook '{h.Event}' is not available for {Title}", true));
        foreach (var n in d.Natives.Where(n => n.Lang != Language))
            d.Diags.Add(new Diag(n.Line, $"native {n.Lang} block skipped: {Title} uses {Language}", true));
        // Свои имена (let, fn, параметры, for), которые в языке движка — ключевые слова: такой код не соберётся.
        var declared = d.Shared.Select(v => (v.Name, Line: 0))
            .Concat(d.Functions.SelectMany(f => f.Params.Select(p => (Name: p, f.Line)).Prepend((f.Name, f.Line))))
            .Concat(d.Hooks.SelectMany(h => h.Body).Concat(d.Functions.SelectMany(f => f.Body)).Where(s => s.Kind is "let" or "for").Select(s => (Name: s.Target, s.Line)));
        foreach (var (name, line) in declared.Where(x => L.Reserved.Contains(x.Name)).DistinctBy(x => x.Name))
            d.Diags.Add(new Diag(line, $"'{name}' is a reserved word in {Language}: rename it, {Title} cannot build this code"));
    }

    protected IEnumerable<string> NativeCode(ModxDoc d) => d.Natives.Where(n => n.Lang == Language).Select(n => n.Code);

    /// <summary>
    /// Тело хука или функции на языке движка. say/log у каждого движка свои. fn — тело своей функции:
    /// там return отдаёт значение (в хуке C# — просто выход из метода).
    /// </summary>
    protected void Body(Code w, List<Stmt> body, Func<string, string> say, Func<string, string> log, bool fn = false)
    {
        var l = L;
        var semi = Language is "javascript" or "csharp" ? ";" : "";
        var indentLang = Language is "python" or "gdscript";
        var lua = Language == "lua";
        // У Lua нет continue: циклу, где он есть, — блок do … end и метка ::mx_continue_N:: в конце.
        var needsLabel = new HashSet<int>();
        {
            var loops = new Stack<int>();
            var n = 0;
            foreach (var s in body)
            {
                if (s.Kind is "while" or "for") loops.Push(++n);
                else if (s.Kind is "if") loops.Push(0);
                else if (s.Kind == "end" && loops.Count > 0) loops.Pop();
                else if (s.Kind == "continue" && loops.FirstOrDefault(x => x > 0) is > 0 and var id) needsLabel.Add(id);
            }
        }
        var empty = new Stack<bool>();
        empty.Push(true);
        var blocks = new Stack<(bool Loop, int Id)>();
        var loopNo = 0;
        void Mark() { empty.Pop(); empty.Push(false); }
        void Line(string s) { w.Line(s + semi); Mark(); }
        void Open(string head) { Mark(); w.Line(head); w.In(); empty.Push(true); }
        void Close() { if (indentLang && empty.Peek()) w.Line("pass"); empty.Pop(); w.Out(); }
        foreach (var s in body)
        {
            switch (s.Kind)
            {
                // let уже объявлен в начале функции (Declare) — здесь это присваивание.
                case "set" or "let": Line($"{s.Target} = {l.Expr(s.Expr)}"); break;
                case "add": Line(Language == "lua" ? $"{s.Target} = {s.Target} + ({l.Expr(s.Expr)})" : $"{s.Target} += {l.Expr(s.Expr)}"); break;
                case "say": Line(say(l.Expr(s.Expr))); break;
                case "log": Line(log(l.Expr(s.Expr))); break;
                case "call": Line(l.Expr(s.Expr)); break;
                case "return":
                {
                    // Метод fn в C# объявлен dynamic: голый return; — ошибка CS0126, нужен return null;.
                    var value = !fn && Language == "csharp" ? "" : s.Expr != "" ? " " + l.Expr(s.Expr) : fn && Language == "csharp" ? " null" : "";
                    // Lua разрешает return только последним в блоке — do … end снимает ограничение.
                    if (lua) { w.Line($"do return{value} end"); Mark(); }
                    else Line("return" + value);
                    break;
                }
                case "break":
                    if (lua) { w.Line("do break end"); Mark(); } else Line("break");
                    break;
                case "continue":
                    if (lua) { w.Line($"goto mx_continue_{blocks.FirstOrDefault(b => b.Loop).Id}"); Mark(); } else Line("continue");
                    break;
                case "if":
                {
                    var c = l.Expr(s.Expr);
                    Open(Language switch { "lua" => $"if {c} then", "python" or "gdscript" => $"if {c}:", _ => $"if ({c}) {{" });
                    blocks.Push((false, 0));
                    break;
                }
                case "elseif":
                {
                    Close();
                    var c = l.Expr(s.Expr);
                    w.Line(Language switch { "lua" => $"elseif {c} then", "python" or "gdscript" => $"elif {c}:", _ => $"}} else if ({c}) {{" });
                    w.In(); empty.Push(true);
                    break;
                }
                case "else":
                    Close();
                    w.Line(Language switch { "lua" => "else", "python" or "gdscript" => "else:", _ => "} else {" });
                    w.In(); empty.Push(true);
                    break;
                case "while" or "for":
                {
                    var e = l.Expr(s.Expr);
                    var head = s.Kind == "while"
                        ? Language switch { "lua" => $"while {e} do", "python" or "gdscript" => $"while {e}:", _ => $"while ({e}) {{" }
                        : Language switch
                        {
                            "lua" => $"for _, {s.Target} in ipairs({e}) do",
                            "python" or "gdscript" => $"for {s.Target} in {e}:",
                            "javascript" => $"for (const {s.Target} of {e}) {{",
                            _ => $"foreach (var {s.Target} in {e}) {{",
                        };
                    var id = ++loopNo;
                    Open(head);
                    if (lua && needsLabel.Contains(id)) { w.Line("do"); w.In(); }
                    blocks.Push((true, id));
                    break;
                }
                case "end":
                {
                    var (loop, id) = blocks.Count > 0 ? blocks.Pop() : (false, 0);
                    Close();
                    if (lua && loop && needsLabel.Contains(id)) { w.Line("end"); w.Line($"::mx_continue_{id}::"); w.Out(); }
                    if (!indentLang) w.Line(lua ? "end" : "}");
                    break;
                }
            }
        }
        if (indentLang && empty.Peek()) w.Line("pass");
    }

    /// <summary>
    /// let в ModScript X живёт до конца хука или функции (так в песочнице и в Python), а в JS, C#, Lua и GDScript —
    /// до конца блока, и второй let с тем же именем там — ошибка. Поэтому каждое имя let объявляется один раз
    /// в начале функции (или метода, куда Unity и Godot сводят хуки одного события), а сами let — присваивания.
    /// </summary>
    protected void Declare(Code w, IEnumerable<List<Stmt>> bodies, IEnumerable<string> pars)
    {
        var own = pars.ToHashSet();
        var names = bodies.SelectMany(b => b).Where(s => s.Kind == "let" && !own.Contains(s.Target)).Select(s => s.Target).Distinct().ToList();
        if (names.Count == 0) return;
        switch (Language)
        {
            case "javascript": w.Line($"let {string.Join(", ", names)};"); break;
            case "lua": w.Line("local " + string.Join(", ", names)); break;
            case "csharp": w.Line("dynamic " + string.Join(", ", names.Select(n => n + " = null")) + ";"); break;
            case "gdscript": foreach (var n in names) w.Line($"var {n}"); break;
        }
    }

    /// <summary>Встроенные функции, которые встречаются в коде (пролог — только из них).</summary>
    protected static HashSet<string> UsedBuiltins(ModxDoc d)
    {
        var used = new HashSet<string>();
        foreach (var s in d.Hooks.SelectMany(h => h.Body).Concat(d.Functions.SelectMany(f => f.Body)))
            foreach (System.Text.RegularExpressions.Match m in System.Text.RegularExpressions.Regex.Matches(s.Expr, @"\b([a-z]+)\s*\("))
                if (ModxDoc.Builtins.Contains(m.Groups[1].Value)) used.Add(m.Groups[1].Value);
        return used;
    }

    /// <summary>Имена, которым хук или функция присваивают значение, но не объявляют сами (для global в Python).</summary>
    protected static List<string> Globals(List<Stmt> body, IEnumerable<string> pars)
    {
        var locals = new HashSet<string>(pars);
        foreach (var s in body.Where(s => s.Kind is "let" or "for")) locals.Add(s.Target);
        return body.Where(s => s.Kind is "set" or "add" && !s.Target.Contains('.') && !s.Target.Contains('[') && !locals.Contains(s.Target))
            .Select(s => s.Target).Distinct().ToList();
    }

