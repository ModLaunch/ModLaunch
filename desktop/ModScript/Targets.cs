    sealed class LuaMods : Target
    {
        public override string Id => "lua";
        public override string Title => "Lua mods (LÖVE and Lua-moddable games)";
        public override string Language => "lua";
        protected override string[] Aliases => ["love"];

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("  ");
            w.Raw(Header(d, "--"));
            w.Line("local M = {}");
            w.Line("-- say: a game can provide modx_host.say to show text in-game; otherwise it prints.");
            w.Line("local say = (modx_host and modx_host.say) or print");
            foreach (var (name, v) in d.Shared) w.Line($"{name} = {L.Literal(v)}");
            Prelude(w, d);
            foreach (var code in NativeCode(d)) w.Block(code);
            Functions(w, d, e => $"say({e})", e => $"print({e})");
            foreach (var h in d.Hooks)
            {
                w.Line($"function M.{h.Event}({(h.Event == "tick" ? "dt" : "")})");
                w.In();
                Body(w, h.Body, e => $"say({e})", e => $"print({e})");
                w.Out();
                w.Line("end");
            }
            w.Line("-- LÖVE: chain into love.load / love.update when they exist.");
            w.Line("if love then");
            w.In();
            if (d.Hooks.Any(h => h.Event == "start")) w.Line("local _load = love.load; love.load = function(...) if _load then _load(...) end M.start() end");
            if (d.Hooks.Any(h => h.Event == "tick")) w.Line("local _update = love.update; love.update = function(dt) if _update then _update(dt) end M.tick(dt) end");
            w.Out();
            w.Line("end");
            if (d.Hooks.Any(h => h.Event == "ready")) w.Line("M.ready()");
            w.Line("return M");
            var dir = gameDir != null && Directory.Exists(Path.Combine(gameDir, "Mods")) ? "Mods" : "mods";
            return [new OutFile($"{dir}/{d.Id}.lua", w.ToString())];
        }
    }

    protected static string Plain(string s) => JsonSerializer.Serialize(s);
}

/// <summary>Писатель кода с отступами.</summary>
public sealed class Code(string unit)
{
    readonly StringBuilder sb = new();
    int depth;
    public void In() => depth++;
    public void Out() => depth = Math.Max(0, depth - 1);
    public void Line(string s) => sb.Append(s == "" ? "" : string.Concat(Enumerable.Repeat(unit, depth)) + s).Append('\n');
    public void Raw(string s) => sb.Append(s);
    /// <summary>Многострочная вставка (native) на текущем отступе.</summary>
    public void Block(string code) { foreach (var l in code.Split('\n')) Line(l); }
    public override string ToString() => sb.ToString();
}
