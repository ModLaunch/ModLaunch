    /// <summary>Свои функции (fn) на языке движка.</summary>
    protected void Functions(Code w, ModxDoc d, Func<string, string> say, Func<string, string> log)
    {
        if (d.Functions.Count == 0) return;
        var lua = Language == "lua";
        // Lua: сначала объявить все имена — функции могут вызывать друг друга в любом порядке.
        if (lua) w.Line("local " + string.Join(", ", d.Functions.Select(f => f.Name)));
        foreach (var f in d.Functions)
        {
            var args = string.Join(", ", Language == "csharp" ? f.Params.Select(p => "dynamic " + p) : f.Params);
            switch (Language)
            {
                case "python":
                    w.Line($"def {f.Name}({args}):");
                    w.In();
                    if (Globals(f.Body, f.Params) is { Count: > 0 } g) w.Line("global " + string.Join(", ", g));
                    Body(w, f.Body, say, log, fn: true);
                    w.Out();
                    break;
                case "gdscript":
                    w.Line($"func {f.Name}({args}):");
                    w.In();
                    Body(w, f.Body, say, log, fn: true);
                    w.Out();
                    break;
                case "lua":
                    w.Line($"{f.Name} = function({args})");
                    w.In();
                    Body(w, f.Body, say, log, fn: true);
                    w.Out();
                    w.Line("end");
                    break;
                case "javascript":
                    w.Line($"function {f.Name}({args}) {{");
                    w.In();
                    Body(w, f.Body, say, log, fn: true);
                    w.Out();
                    w.Line("}");
                    break;
                default:
                    w.Line($"dynamic {f.Name}({args})");
                    w.Line("{");
                    w.In();
                    Body(w, f.Body, say, log, fn: true);
                    if (f.Body.LastOrDefault()?.Kind != "return") w.Line("return null;");
                    w.Out();
                    w.Line("}");
                    break;
            }
        }
    }

    // ---------------------------------------------------------------- Ren'Py

    sealed class RenPy : Target
    {
        public override string Id => "renpy";
        public override string Title => "Ren'Py";
        public override string Language => "python";

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("    ");
            w.Raw(Header(d, "#"));
            w.Line("init 999 python:");
            w.In();
            foreach (var (name, v) in d.Shared) w.Line($"{name} = {L.Literal(v)}");
            Prelude(w, d);
            foreach (var code in NativeCode(d)) w.Block(code);
            Functions(w, d, e => $"renpy.notify({e})", e => $"print({e})");
            foreach (var h in d.Hooks)
            {
                var fn = $"_modx_{d.Id}_{h.Event}";
                w.Line($"def {fn}(*args):");
                w.In();
                var globals = Globals(h.Body, []);
                if (globals.Count > 0) w.Line("global " + string.Join(", ", globals));
                Body(w, h.Body, e => $"renpy.notify({e})", e => $"print({e})");
                w.Out();
                w.Line(h.Event switch
                {
                    "ready" => $"{fn}()",
                    "start" => $"config.start_callbacks.append({fn})",
                    "load" => $"config.after_load_callbacks.append({fn})",
                    _ => $"config.periodic_callbacks.append({fn})",
                });
            }
            if (d.Shared.Count == 0 && d.Hooks.Count == 0 && d.Functions.Count == 0 && !NativeCode(d).Any()) w.Line("pass");
            return [new OutFile($"game/modscript_{d.Id}.rpy", w.ToString())];
        }
    }

    // ---------------------------------------------------------------- RPG Maker MV / MZ

    sealed class RpgMaker : Target
    {
        public override string Id => "rpgmaker";
        public override string Title => "RPG Maker MV/MZ";
        public override string Language => "javascript";
        protected override string[] Aliases => ["rpgmv", "rpgmz"];

        /// <summary>У MV скрипты лежат в www/js, у MZ — сразу в js.</summary>
        static string JsDir(string? gameDir) => gameDir != null && Directory.Exists(Path.Combine(gameDir, "www", "js")) ? "www/js" : "js";
        static string PluginName(string id) => "ModScript_" + id;

        public override List<OutFile> Emit(ModxDoc d, string? gameDir)
        {
            Warn(d);
            var w = new Code("  ");
            w.Raw("//=============================================================================\n");
            w.Raw(Header(d, "//"));
            w.Raw("//=============================================================================\n");
            w.Raw($"/*:\n * @target MZ\n * @plugindesc {(d.About != "" ? d.About : d.Name)} (ModScript X)\n * @author {(d.Author != "" ? d.Author : "ModScript X")}\n */\n");
            w.Line("(() => {");
            w.In();
            w.Line("\"use strict\";");
            foreach (var (name, v) in d.Shared) w.Line($"let {name} = {L.Literal(v)};");
            Prelude(w, d);
            foreach (var code in NativeCode(d)) w.Block(code);
            Functions(w, d, e => $"$gameMessage.add(String({e}))", e => $"console.log({e})");
            foreach (var h in d.Hooks)
            {
                w.Line($"const {h.Event} = () => {{");
                w.In();
                Body(w, h.Body, e => $"$gameMessage.add(String({e}))", e => $"console.log({e})");
                w.Out();
                w.Line("};");
                var (owner, method, args) = h.Event switch
                {
                    "start" => ("DataManager", "setupNewGame", ""),
                    "load" => ("DataManager", "extractSaveContents", "contents"),
                    "tick" => ("Scene_Map.prototype", "update", ""),
                    _ => ("", "", ""),
                };
                if (owner == "") { w.Line($"{h.Event}();"); continue; }
                var saved = $"_{h.Event}_{method}";
                w.Line($"const {saved} = {owner}.{method};");
                w.Line($"{owner}.{method} = function({args}) {{");
                w.In();
                w.Line($"const result = {saved}.apply(this, arguments);");
                w.Line($"{h.Event}();");
                w.Line("return result;");
                w.Out();
                w.Line("};");
            }
            w.Out();
            w.Line("})();");
            return [new OutFile($"{JsDir(gameDir)}/plugins/{PluginName(d.Id)}.js", w.ToString())];
        }

        /// <summary>Плагин включается записью в js/plugins.js — как это делает сам редактор RPG Maker.</summary>
        public override string? AfterInstall(ModxDoc d, string gameDir)
        {
            var path = Path.Combine(gameDir, JsDir(gameDir), "plugins.js");
            if (!File.Exists(path)) return "plugins.js not found: enable the plugin in the RPG Maker editor";
            var text = File.ReadAllText(path);
            var name = PluginName(d.Id);
            if (text.Contains($"\"name\":\"{name}\"")) return null;
            var close = text.LastIndexOf(']');
            if (close < 0) return "plugins.js has an unexpected format: enable the plugin in the RPG Maker editor";
            var entry = new JsonObject { ["name"] = name, ["status"] = true, ["description"] = d.About, ["parameters"] = new JsonObject() }.ToJsonString();
            var before = text[..close].TrimEnd();
            var sep = before.EndsWith('[') ? "\n" : ",\n";
            File.WriteAllText(path, before + sep + entry + "\n" + text[close..]);
            return $"registered {name} in plugins.js";
        }

        public override void AfterEject(string id, string gameDir)
        {
            var path = Path.Combine(gameDir, JsDir(gameDir), "plugins.js");
            if (!File.Exists(path)) return;
            var lines = File.ReadAllLines(path).ToList();
            var i = lines.FindIndex(l => l.Contains($"\"name\":\"{PluginName(id)}\""));
            if (i < 0) return;
            lines.RemoveAt(i);
            // Убрать висячую запятую у предыдущей записи, если удалили последнюю.
            if (i < lines.Count && lines[i].TrimStart().StartsWith(']') && i > 0) lines[i - 1] = lines[i - 1].TrimEnd().TrimEnd(',');
            File.WriteAllLines(path, lines);
        }
    }

